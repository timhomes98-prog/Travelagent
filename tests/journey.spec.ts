import { test, expect } from '@playwright/test';
test('plan, customise, budget, persist and book a sample trip',async({page})=>{
 const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('/');await expect(page.getByRole('heading',{name:/A little less planning/})).toBeVisible();
 await page.getByRole('button',{name:'Let’s plan your escape'}).click();
 await page.getByLabel('Your destination').selectOption('Kyoto');
 await page.getByLabel('How many days?').fill('3');
 await page.getByLabel('Travellers',{exact:true}).fill('2');
 await page.getByLabel('Total budget (£, all travellers)').fill('1500');
 await page.getByRole('button',{name:'A few more details'}).click();
 await page.getByLabel('Your travel pace').selectOption('Relaxed');
 await page.getByRole('button',{name:'Create my sample trip'}).click();
 await expect(page.getByRole('heading',{name:'Kyoto, your way.'})).toBeVisible();
 await expect(page.getByLabel('Activity 1 name')).toHaveValue('Explore the lanes of Higashiyama');
 await expect(page.locator('.activity')).toHaveCount(2);
 await page.getByLabel('Activity 1 name').fill('Tea ceremony with friends');
 await page.getByRole('button',{name:'Day 2',exact:true}).click();await expect(page.locator('.activity')).toHaveCount(2);
 await page.getByRole('button',{name:/Remove/}).first().click();await expect(page.locator('.activity')).toHaveCount(1);
 await page.getByRole('button',{name:'Add a stop'}).click();await expect(page.locator('.activity')).toHaveCount(2);
 await page.getByLabel('Total trip budget (£)').fill('100');await expect(page.getByText(/over budget/)).toBeVisible();
 await expect(page.getByRole('link',{name:'Hotels',exact:true})).toHaveAttribute('href',/Kyoto/);
 await expect(page.getByRole('link',{name:'Open destination in Google Maps'})).toHaveAttribute('href',/query=Kyoto/);
 await page.reload();await page.getByRole('button',{name:'My trips',exact:true}).count();
 if(test.info().project.name==='mobile')await page.getByRole('button',{name:'Toggle navigation'}).click();
 await page.getByRole('button',{name:'My trips',exact:true}).click();await expect(page.getByLabel('Activity 1 name')).toHaveValue('Tea ceremony with friends');
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBeTruthy();
 expect(errors).toEqual([]);
 await page.screenshot({path:`test-results/${test.info().project.name}-trip.png`,fullPage:true});
});
